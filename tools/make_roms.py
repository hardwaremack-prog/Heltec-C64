#!/usr/bin/env python3
"""Embed ROM files as the firmware's built-in fallback set.
Usage: python3 make_roms.py basic.rom kernal.rom chargen.rom [out.h]
By default the Open ROMs (LGPL-3) are embedded. You can embed your own
licensed Commodore ROMs instead, but normally you just upload them from
the board's web page -- no rebuild needed."""
import sys, zlib
b, k, c = sys.argv[1:4]
out = sys.argv[4] if len(sys.argv) > 4 else "builtin_roms.h"
def arr(name, path, size):
    d = open(path, "rb").read()
    assert len(d) == size, f"{path}: expected {size} bytes, got {len(d)}"
    rows = ",\n".join("  " + ",".join(f"0x{x:02X}" for x in d[i:i+24]) for i in range(0, len(d), 24))
    return f"// {path}  CRC32 {zlib.crc32(d):08X}\nstatic const uint8_t {name}[{size}] = {{\n{rows}\n}};\n"
with open(out, "w") as f:
    f.write("// Generated by tools/make_roms.py -- built-in fallback ROM set\n#pragma once\n#include <stdint.h>\n")
    f.write('#define BUILTIN_ROM_NAME "Open ROMs (MEGA65 project, LGPL-3)"\n')
    f.write(arr("BUILTIN_BASIC", b, 8192)); f.write(arr("BUILTIN_KERNAL", k, 8192)); f.write(arr("BUILTIN_CHARGEN", c, 4096))
print("wrote", out)
